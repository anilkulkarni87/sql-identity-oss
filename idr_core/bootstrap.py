"""
Autonomous configuration bootstrapper for SQL Identity Resolution.

Profiles warehouse datasets, discovers tables and columns, infers entity keys,
watermarks, customer identifiers, survivorship rules, and poison-pill exclusions,
and outputs a production-ready declarative YAML manifest.
"""

from typing import Any, Dict, List, Optional
import yaml

from idr_core.profiler import IDRDataProfiler, is_system_table


class AutoBootstrapper:
    """Discovers and profiles tables in a warehouse and generates an IDR YAML manifest."""

    def __init__(self, adapter: Any):
        self.adapter = adapter
        self.profiler = IDRDataProfiler(adapter)

    def bootstrap(
        self,
        schema: Optional[str] = None,
        candidate_tables: Optional[List[str]] = None,
        sample_size: int = 500,
        output_path: Optional[str] = "idr_config.yaml",
        apply_to_warehouse: bool = False,
    ) -> Dict[str, Any]:
        """
        Scan warehouse tables, profile actual data distributions, synthesize
        a complete declarative configuration, write to YAML, and optionally apply to idr_meta.
        """
        # 1. Discover candidate tables if not explicitly provided
        tables = candidate_tables
        if not tables:
            tables = self._discover_tables(schema)

        if not tables:
            return {
                "status": "NO_TABLES_FOUND",
                "message": f"No candidate tables found in schema/dataset '{schema or 'default'}'.",
                "suggested_config": None,
            }

        # 2. Run statistical profiler
        profiling_result = self.profiler.profile_and_generate_config(
            tables, sample_size=sample_size
        )

        suggested_config = profiling_result.get("suggested_config")
        if not suggested_config or not suggested_config.get("sources"):
            return {
                "status": "NO_SOURCES_IDENTIFIED",
                "message": "Profiling completed, but no tables contained valid customer identifiers (email, phone, loyalty, customer_id).",
                "profiling_diagnostics": profiling_result.get("profiling_diagnostics", {}),
                "suggested_config": None,
            }

        # 3. Write to YAML output file if requested
        if output_path:
            with open(output_path, "w", encoding="utf-8") as f:
                f.write("# =====================================================================\n")
                f.write("# SQL Identity Resolution (IDR) - Production Configuration\n")
                f.write(f"# Auto-generated by `idr bootstrap --auto` across {len(suggested_config['sources'])} tables\n")
                f.write("# =====================================================================\n\n")
                yaml.dump(suggested_config, f, sort_keys=False, default_flow_style=False, indent=2)

        # 4. Optionally apply directly to idr_meta
        applied = False
        apply_error = None
        if apply_to_warehouse:
            try:
                from idr_core.config import config_to_sql

                dialect = getattr(self.adapter, "dialect", getattr(self.adapter, "platform", "duckdb"))
                statements = config_to_sql(suggested_config, dialect=dialect)
                for stmt in statements:
                    self.adapter.execute(stmt)
                applied = True
            except Exception as e:
                applied = False
                apply_error = str(e)

        return {
            "status": "SUCCESS",
            "tables_scanned": len(tables),
            "sources_configured": len(suggested_config["sources"]),
            "rules_generated": len(suggested_config.get("rules", [])),
            "survivorship_rules": len(suggested_config.get("survivorship", [])),
            "exclusions_discovered": len(suggested_config.get("exclusions", [])),
            "output_path": output_path,
            "applied_to_warehouse": applied,
            "apply_error": apply_error,
            "suggested_config": suggested_config,
            "profiling_diagnostics": profiling_result.get("profiling_diagnostics", {}),
        }

    def _discover_tables(self, schema: Optional[str] = None) -> List[str]:
        """Fetch candidate tables from warehouse adapter, filtering system catalogs."""
        try:
            if hasattr(self.adapter, "list_tables"):
                raw_tables = self.adapter.list_tables(schema=schema)
                return [t for t in raw_tables if not is_system_table(t)]
        except Exception:
            pass

        # Fallback queries by dialect
        dialect = getattr(self.adapter, "dialect", getattr(self.adapter, "platform", "duckdb"))
        try:
            if dialect == "duckdb":
                sql = (
                    "SELECT table_schema || '.' || table_name AS fqn "
                    "FROM information_schema.tables "
                    "WHERE table_schema NOT IN ('idr_meta', 'idr_work', 'idr_out', 'information_schema') "
                    "AND table_type = 'BASE TABLE'"
                )
                rows = self.adapter.query(sql)
                return [r["fqn"] for r in rows if isinstance(r, dict)]
        except Exception:
            pass

        return []
